'use strict';

class BaseService {

  /**
   * ---------------------------------------------------------------------------
   * Constructor
   * ---------------------------------------------------------------------------
   */
  constructor(serviceName) {

    if (!serviceName) {
      throw new Error("Service name is required.");
    }

    this._name = serviceName;
    this._initialized = false;
    this._createdAt = new Date();
    this._version = ERPConfig.VERSION;

  }

  /**
   * ---------------------------------------------------------------------------
   * Initialize Service
   * ---------------------------------------------------------------------------
   */
  initialize() {

    this._initialized = true;

    return this;

  }

  /**
   * ---------------------------------------------------------------------------
   * Dispose Service
   * ---------------------------------------------------------------------------
   */
  dispose() {

    this._initialized = false;

    return this;

  }

  /**
   * ---------------------------------------------------------------------------
   * Validate
   * ---------------------------------------------------------------------------
   */
  validate() {

    return true;

  }

  /**
   * ---------------------------------------------------------------------------
   * Before Save Hook
   * ---------------------------------------------------------------------------
   */
  beforeSave(data) {

    return data;

  }

  /**
   * ---------------------------------------------------------------------------
   * After Save Hook
   * ---------------------------------------------------------------------------
   */
  afterSave(data) {

    return data;

  }

  /**
   * ---------------------------------------------------------------------------
   * Before Delete Hook
   * ---------------------------------------------------------------------------
   */
  beforeDelete(id) {

    return id;

  }

  /**
   * ---------------------------------------------------------------------------
   * After Delete Hook
   * ---------------------------------------------------------------------------
   */
  afterDelete(id) {

    return id;

  }

  /**
   * ---------------------------------------------------------------------------
   * Log
   * ---------------------------------------------------------------------------
   */
  log(message) {

    if (WEF.Config.get("ENABLE_LOGGING")) {

      Logger.log("[" + this._name + "] " + message);

    }

  }

  /**
   * ---------------------------------------------------------------------------
   * Error
   * ---------------------------------------------------------------------------
   */
  error(message) {

    throw new Error("[" + this._name + "] " + message);

  }

  /**
   * ---------------------------------------------------------------------------
   * Service Name
   * ---------------------------------------------------------------------------
   */
  getName() {

    return this._name;

  }

  /**
   * ---------------------------------------------------------------------------
   * Version
   * ---------------------------------------------------------------------------
   */
  getVersion() {

    return this._version;

  }

  /**
   * ---------------------------------------------------------------------------
   * Created Time
   * ---------------------------------------------------------------------------
   */
  getCreatedTime() {

    return this._createdAt;

  }

  /**
   * ---------------------------------------------------------------------------
   * Initialized
   * ---------------------------------------------------------------------------
   */
  isInitialized() {

    return this._initialized;

  }

  /**
   * ---------------------------------------------------------------------------
   * Runtime
   * ---------------------------------------------------------------------------
   */
  runtime() {

    return Object.assign({}, WEF.Runtime);

  }

  /**
   * ---------------------------------------------------------------------------
   * Spreadsheet
   * ---------------------------------------------------------------------------
   */
  spreadsheet() {

    return SpreadsheetApp.getActiveSpreadsheet();

  }

  /**
   * ---------------------------------------------------------------------------
   * Spreadsheet Id
   * ---------------------------------------------------------------------------
   */
  spreadsheetId() {

    return SpreadsheetApp.getActiveSpreadsheet().getId();

  }

  /**
   * ---------------------------------------------------------------------------
   * Active User
   * ---------------------------------------------------------------------------
   */
  user() {

    return Session.getActiveUser().getEmail();

  }

  /**
   * ---------------------------------------------------------------------------
   * Timezone
   * ---------------------------------------------------------------------------
   */
  timezone() {

    return Session.getScriptTimeZone();

  }

  /**
   * ---------------------------------------------------------------------------
   * Health Check
   * ---------------------------------------------------------------------------
   */
  health() {

    return {

      service: this.getName(),

      initialized: this.isInitialized(),

      version: this.getVersion(),

      status: this.isInitialized()
        ? "READY"
        : "NOT_READY"

    };

  }

    /**
   * ---------------------------------------------------------------------------
   * Service Information
   * ---------------------------------------------------------------------------
   */
  info() {

    return {

      service: this.getName(),

      version: this.getVersion(),

      initialized: this.isInitialized(),

      created: this.getCreatedTime()

    };

  }

}

/**
 * =============================================================================
 * Example Service
 * =============================================================================
 */

class ExampleService extends BaseService {

  constructor() {

    super("ExampleService");

  }

  hello() {

    this.log("Hello Workspace ERP");

    return "Hello Workspace ERP";

  }

}



